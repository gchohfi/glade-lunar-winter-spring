function starsForMission(passed, wrong, elapsedMs, timeLimitMs) {
	if (!passed) return 0;
	if (wrong === 0 && elapsedMs <= timeLimitMs * .7) return 3;
	if (wrong <= 1) return 2;
	return 1;
}
function xpForMission(input) {
	const combo = Math.max(0, Math.min(10, input.bestCombo));
	if (!input.passed) return 8 + input.correct * 4;
	const timeLeft = Math.max(0, 1 - input.elapsedMs / Math.max(1, input.timeLimitMs));
	const timeBonus = Math.round(timeLeft * 28);
	return 48 + input.correct * 4 + combo * 4 + Math.max(0, 8 - input.wrong) * 3 + timeBonus;
}
function applyXp(level, xp, gained) {
	let nextLevel = Math.max(1, level);
	let nextXp = Math.max(0, xp) + Math.max(0, gained);
	let gainedLevels = 0;
	while (nextLevel < 30 && nextXp >= xpToNext(nextLevel)) {
		nextXp -= xpToNext(nextLevel);
		nextLevel += 1;
		gainedLevels += 1;
	}
	return {
		level: nextLevel,
		xp: nextXp,
		levelsGained: gainedLevels
	};
}
